import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from '../frontend/node_modules/typescript/lib/typescript.js';

const source=await readFile(new URL('../frontend/src/audio-events.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {SoundEvents,combatAudibility}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const state={id:'match',you:'me',status:'Running',world:{armies:[],convoys:[],notices:[],alerts:[],threats:[],oases:[{id:'oasis',ownerId:null,villageId:null},{id:'mine',ownerId:'me',villageId:'home'}],warfare:{settlements:[{id:'city',ownerId:'enemy',ruined:false}],battles:[],sieges:[]}}};
const events=new SoundEvents();
assert.deepEqual(events.update(state),[],'Initial world is silent');
state.world.threats=[{armyId:'enemy-army',ownerId:'enemy'}];
state.world.notices.push({id:1,kind:'war',text:'An enemy army is marching on your village.'});
state.world.alerts.push({id:2,kind:'oasis-attack',text:'Enemy troops are marching on your oasis.'});
assert.deepEqual(events.update(state),['attack'],'One cue for overlapping attack notifications in a snapshot');
assert.deepEqual(events.update(state),[],'Repeated snapshots do not repeat alerts');
state.world.oases[0].ownerId='me';
assert.deepEqual(events.update(state),['oasis-captured']);
state.world.oases[0].villageId='new-home';
assert.deepEqual(events.update(state),[],'Moving an owned oasis to another village is not a capture');
state.world.warfare.settlements[0].ownerId='me';
assert.deepEqual(events.update(state),['village-captured']);
state.world.oases[1].ownerId='enemy';
state.world.notices.push({id:3,kind:'oasis-loss',text:'Your oasis was captured.'});
state.world.alerts.push({id:3,kind:'oasis-loss',text:'Your oasis was captured.'});
assert.deepEqual(events.update(state),['oasis-lost'],'Ownership and matching history play one loss cue');
state.world.alerts.push({id:1,kind:'oasis-attack',text:'An older alert'});
assert.deepEqual(events.update(state),[],'Old inbox history cannot replay alerts');
state.world.threats=[];events.update(state);
state.world.armies=[{id:'oasis-raider',ownerId:'enemy',order:'Occupying',targetId:'oasis'}];
assert.deepEqual(events.update(state),['attack'],'Oasis attacks are detected before engagement');
state.world.armies.push({id:'ours',ownerId:'me',order:'Attacking',targetId:'mine'});
assert.deepEqual(events.update(state),[],'Own outgoing attacks do not sound the incoming alarm');
events.reset();assert.deepEqual(events.update(state),[],'Reconnect establishes a quiet baseline');
state.id='other-match';assert.deepEqual(events.update(state),[],'Switching matches resets sound history');
state.status='Finished';assert.deepEqual(events.update(state),[]);
assert.deepEqual(events.update(null),[]);
assert.deepEqual(combatAudibility(500,300,1000,600),{level:1,pan:0});
assert(combatAudibility(680,300,1000,600).pan>0);
assert(combatAudibility(320,300,1000,600).pan<0);
assert(combatAudibility(680,300,1000,600).level<combatAudibility(540,300,1000,600).level);
assert.equal(combatAudibility(920,300,1000,600),null,'Battles near screen edges far from camera center are silent');
assert.equal(combatAudibility(5,5,1000,600),null,'Battles in screen corners are silent');
for(const [x,y,w,h] of [[-1,100,1000,600],[1001,100,1000,600],[100,-1,1000,600],[100,601,1000,600],[0,0,0,0]])assert.equal(combatAudibility(x,y,w,h),null);
console.log('Passed audio event checks: capture/loss/attack transitions, deduplication, quiet reconnects, camera falloff and stereo position.');
